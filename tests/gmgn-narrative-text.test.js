const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const test = require('node:test');
const { runInNewContext } = require('node:vm');

const source = readFileSync(require.resolve('../content.js'), 'utf8');
const markers = source.slice(source.indexOf('  const AI_NARRATIVE_FOOTER'), source.indexOf('  const AI_NARRATIVE_TOOLTIP'));
const parser = source.slice(source.indexOf('  function readAiNarrativeText'), source.indexOf('  function narrativeLabel'));
const read = runInNewContext(markers + parser + '\nreadAiNarrativeText');

test('an explicit narrative footer takes precedence over AI wording in the summary', () => {
  const english = 'AI-generated artwork inspired the token.';
  assert.equal(read(english + '\nDisclaimer: This content was generated by AI.'), english);
  const chinese = '代币来自一张猫的照片。';
  assert.equal(read(chinese + '免责声明：以上内容由 AI 生成，仅供参考。'), chinese);
  assert.equal(read(chinese + '免責聲明：本內容由人工智慧生成。'), chinese);
  assert.equal(read('loading...'), null);
  assert.equal(read('The token uses AI-generated artwork.'), null);
  assert.equal(read('代币来自一个AI生成内容平台。'), null);
  assert.equal(read(chinese + 'AI生成内容，仅供参考。'), chinese);
  assert.equal(read('免责声明：内容由 AI 生成。'), null);
});
